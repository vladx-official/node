// VladX: Italian names for the JavaScript and Node.js standard library.
//
// Every entry maps an Italian name to the existing (English) name. The Italian
// name becomes an alias of the very same function/object, so
// `[1, 2].mappa(f)` is exactly `[1, 2].map(f)`.
//
// Kinds of tables:
// - `alias`: copies the property descriptor of the English name (methods,
//   static functions, constants, accessors that live on the target).
// - `istanza`: for properties that live on each instance (e.g. `length` of an
//   array, `message` of an error). An accessor is added on the prototype that
//   reads/writes the English property of `this`.
//
// The targets are resolved lazily by name from globalThis, so a missing
// global (e.g. with --no-browser-globals) is simply skipped.

